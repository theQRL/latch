import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const text = (path) => readFile(new URL(path, root), 'utf8');
const config = await text('netlify.toml');
assert.match(config, /publish\s*=\s*"apps\/pwa\/dist"/);
assert.match(config, /command\s*=\s*"npm ci && npm test && npm run build:pwa"/);
assert.match(config, /pretty_urls\s*=\s*false/);
assert.ok(!/^\s*from\s*=\s*"\/\*"/m.test(config), 'Do not hide missing files behind a catch-all rewrite');
const headers = await text('apps/pwa/dist/_headers');
assert.equal(headers, await text('shared/assets/_headers'));
const csp = headers.match(/^  Content-Security-Policy: (.+)$/m)?.[1];
const meta = (await text('apps/pwa/dist/index.html')).match(/http-equiv="Content-Security-Policy"\s+content="([^"]+)"/)?.[1];
assert.equal(csp, `${meta}; frame-ancestors 'none'`, 'HTTP and HTML CSP must agree');
assert.match(headers, /screen-wake-lock=\(self\)/);
assert.match(headers, /camera=\(self\)/);
assert.match(headers, /Cache-Control: no-cache, max-age=0, must-revalidate/);
assert.match(headers, /Service-Worker-Allowed: \//);
const manifest = JSON.parse(await text('apps/pwa/dist/manifest.webmanifest'));
for (const key of ['id', 'scope', 'start_url']) assert.equal(manifest[key], '/');
assert.equal(manifest.name, 'QRL Latch');
assert.ok((await text('apps/pwa/dist/sw.js')).startsWith('self.__LATCH_DIGESTS__='));
console.log('Verified hosting configuration, CSP, root-scope manifest and copied Netlify headers.');
